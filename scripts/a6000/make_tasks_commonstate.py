"""Common-state action-source tasks (W100a, docs/insights/COMMONSTATE_SOURCES_PROTOCOL.md), fork_driver mode
`commonstate`. q8 U2B Bank U states f01-f03; new action source GPTQ-W4 d2.

  type A  cs_*_d2_bf16: servers B = BF16, Q = d2; arm QB = a_d2 -> BF16; reference re-run bf16_orig (BB no-op)
  type B  cs_*_d2_d1:   servers B = d2,   Q = d1; arm BQ = a_d2 -> d1;   reference re-run d1_native (QQ vs Bank U)
  --gate    two gate tasks (12 hash-selected rows, every row re-run), node005 / node007
  --panel   six panel tasks (one per block x type), deps on both gates, node004/005/007 in rotation
Priority -29. Never overwrites an existing id.
W100u (amendment A1; manifests commonstate_q8ext_v1.json / commonstate_q4_v1.json; priority -28, no node pin):
  --design q8ext --ref    q8 f04-f06 d1 reference arms: bank_u U2B on newmethod_panel_v1 rows -> commonstate/q8/ref_d1/<blk>
  --design q8ext --panel  q8 f04-f06 d2 tasks, each depending on its block's reference task (no new gate, A1.1)
  --design q4 --gate      q4 gates (fail loudly, autopilot_retry no); --design q4 --panel: six q4 tasks, deps on both gates
usage: python scripts/a6000/make_tasks_commonstate.py [--design v1|q8ext|q4] (--gate | --panel | --ref) [--write]
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path("/data/ziyangs/cloq")
Q = Path("/data/ziyangs/cloq_work/queue")
MAN = ROOT / "manifests/fork/commonstate_v1.json"
DESIGNS = {"v1": MAN, "q8ext": ROOT / "manifests/fork/commonstate_q8ext_v1.json", "q4": ROOT / "manifests/fork/commonstate_q4_v1.json"}
PRIO = -29
NODES = ("node004", "node005", "node007")
BF16 = {"kind": "bf16"}


def ck(c: str, m: str = "q8") -> dict:
    return {"kind": "gptq", "wbits": 4, "calib": f"manifests/a6k2/{m}/calib_fp_traj_{c}.json"}


def types(m: str) -> dict:
    return {
        "d2_bf16": {"B": BF16, "Q": ck("c2", m), "action_handle": "Q", "cont_handle": "B", "ref_rerun": "bf16_orig",
                    "cont_label": "bf16", "idcheck": {"Q": [[f"a6k2_{m}_gptq_w4_d2_n1", d] for d in ("retail", "airline")],
                                                      "B": [[f"a6k2_{m}_bfpair_f01", d] for d in ("retail", "airline")]}},
        "d2_d1": {"B": ck("c2", m), "Q": ck("c1", m), "action_handle": "B", "cont_handle": "Q", "ref_rerun": "d1_native",
                  "cont_label": "gptq_w4_d1", "idcheck": {"B": [[f"a6k2_{m}_gptq_w4_d2_n1", d] for d in ("retail", "airline")],
                                                          "Q": [[f"a6k2_{m}_gptq_w4_d1_f01", d] for d in ("retail", "airline")]}},
    }


TYPES = types("q8")


def task(tid: str, typ: str, node: str | None, blocks: list[str], out: str, gate: bool, deps: list[str], man: dict) -> dict:
    m = man.get("model", "q8")
    T = types(m)[typ]
    fork = {"mode": "commonstate", "manifest": man["bank_manifest"], "manifest_sha256": man["bank_manifest_sha256"],
            "model": m, "blocks": blocks, "subs": ["U2B"], "ref_dir": man["ref_dir"],
            "action_handle": T["action_handle"], "cont_handle": T["cont_handle"], "ref_rerun": T["ref_rerun"],
            "source_label": "gptq_w4_d2", "cont_label": T["cont_label"], "noop_frac": man["noop_frac"],
            "concurrency": 8, "resume": True, "out": out}
    if gate:
        fork.update(gate=True, limit=man["gate_rows"], idcheck=T["idcheck"], idcheck_n=16)
    t = {"node": node, "id": tid, "kind": "fork", "model": m, "gpus": man.get("gpus", 2), "priority": man.get("priority", PRIO),
         "deps": deps, "B": {"ckpt": T["B"]}, "Q": {"ckpt": T["Q"]}, "expect_distinct_numerics": True, "fork": fork,
         "note": f"W100a common-state action sources ({typ}: a_d2 -> {T['cont_label']}), blocks {blocks}; "
                 "COMMONSTATE_SOURCES_PROTOCOL.md; generated by make_tasks_commonstate.py"}
    if "protocol_amendment" in man:  # W100u designs only (v1 tasks unchanged)
        t["note"] = t["note"].replace("W100a", f"W100u {m}", 1) + f" --design {m if m == 'q4' else 'q8ext'} (amendment {man['protocol_amendment']})"
        if man.get("gpu_util"):
            t["gpu_util"] = man["gpu_util"]
        if gate:
            fork["fail_loud"] = True
            t["autopilot_retry"] = "no: common-state gate, fails loudly; a failure goes to a human (A1.4)"
    return t


def ref_task(blk: str, man: dict) -> dict:
    """A1.1: this study's own q8 d1 reference arms (BB/BQ/QB/QQ) at an f04-f06 block = the NEWMETHOD phase-2 reference-cell
    bank_u spec with a different output directory."""
    r = man["ref_task"]
    fork = {"mode": r["mode"], "manifest": man["bank_manifest"], "manifest_sha256": man["bank_manifest_sha256"], "model": "q8",
            "cell": r["cell"], "blocks": [blk], "subs": ["U2B"], "noop_frac": r["noop_frac"], "concurrency": 8,
            "out": f"{man['ref_dir']}/{blk}"}
    return {"node": None, "id": r["id"].format(blk=blk), "kind": "fork", "model": "q8", "gpus": 2, "priority": man["priority"],
            "deps": [], "B": {"ckpt": BF16}, "Q": {"ckpt": ck("c1")}, "fork": fork,
            "note": f"W100u q8 common-state d1 reference arms, block {blk} (amendment {man['protocol_amendment']}, A1.1); "
                    "never enters a NEWMETHOD analysis; generated by make_tasks_commonstate.py --design q8ext --ref"}


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--gate", action="store_true")
    g.add_argument("--panel", action="store_true")
    g.add_argument("--ref", action="store_true", help="--design q8ext: the d1 reference tasks")
    ap.add_argument("--design", choices=sorted(DESIGNS), default="v1")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    man = json.load(open(DESIGNS[a.design]))
    gates = [f"cs_gate_q8_{t}" for t in TYPES]
    tasks = []
    if a.design != "v1":
        psha = hashlib.sha256((ROOT / man["protocol"]).read_bytes()).hexdigest()
        if psha != man["protocol_sha256"]:
            raise SystemExit(f"protocol sha256 {psha} != {man['protocol_sha256']} recorded in {DESIGNS[a.design].name}: refusing")
        m, blocks = man["model"], man["blocks"]
        if a.design == "q8ext" and a.gate or a.design == "q4" and a.ref:
            raise SystemExit("no such task set (A1.1: q8ext has no gate; A1.4: q4 reuses Bank U q4 reference arms)")
        if a.ref:
            tasks = [ref_task(b, man) for b in blocks]
        elif a.gate:
            tasks = [task(f"cs_gate_{m}_{t}", t, None, blocks, f"{man['gate_dir']}/{t}", True, [], man) for t in TYPES]
        else:
            for b in blocks:
                deps = gates + [man["ref_task"]["id"].format(blk=b)] if a.design == "q8ext" else [f"cs_gate_{m}_{t}" for t in TYPES]
                tasks += [task(f"cs_{m}_{t}_{b}", t, None, [b], f"{man['panel_dir']}/{t}/{b}", False, deps, man) for t in TYPES]
    elif a.ref:
        raise SystemExit("--ref needs --design q8ext")
    elif a.gate:
        for (typ, node), tid in zip((("d2_bf16", "node005"), ("d2_d1", "node007")), gates):
            tasks.append(task(tid, typ, node, man["blocks"], f"analysis/fork/commonstate/q8/gate/{typ}", True, [], man))
    else:
        i = 0
        for b in man["blocks"]:
            for typ in TYPES:
                tasks.append(task(f"cs_q8_{typ}_{b}", typ, NODES[i % len(NODES)], [b],
                                  f"analysis/fork/commonstate/q8/panel/{typ}/{b}", False, gates, man))
                i += 1
    for t in tasks:
        print(t["id"], t.get("node"), t["fork"]["blocks"], t["fork"]["out"])
    if not a.write:
        print(f"{len(tasks)} tasks (dry run)")
        return
    n = 0
    for t in tasks:
        if any((Q / d / f"{t['id']}.json").exists() for d in ("todo", "running", "done", "failed", "deferred")):
            print("exists, skipped:", t["id"])
            continue
        p = Q / "todo" / f"{t['id']}.json"
        tmp = p.with_suffix(".tmp")
        tmp.write_text(json.dumps(t, indent=1))
        tmp.replace(p)
        n += 1
    print(f"wrote {n} tasks to {Q / 'todo'}")


if __name__ == "__main__":
    main()
