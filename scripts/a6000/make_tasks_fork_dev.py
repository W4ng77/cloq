"""PROPOSED development-fork task generator (protocol fork-v1). Prints only; `--write` queues, and must not be used
before the engineering gate has passed (docs/insights/FORK_PROTOCOL.md §8) and the go decision is recorded.

Cells and blocks come from manifests/fork/dev_blocks_v1.json (fixed 2026-09-30 before any fork outcome):
  primary checkpoint rule: per model x method, the W4 checkpoint with the most existing fresh-nonce draws; tie -> lowest
  calibration draw index  =>  gptq_w4_d1 and awq_w4 (both calibration c1) on q4 and q8. Not chosen by results.
  blocks: existing q3, q4, q5 + new f01..f17 = 20 per cell; each block = retail (58) + airline (27) = 85 tasks.
One task = one cell x a group of `--per-task` blocks (checkpoint built once per task). It runs mode "dev": divergence
search over all 85 tasks of every block, all states frozen, then BB/BQ/QB on each state plus the QQ no-op on a 10%
hash sample. A task waits for the eval tasks that produce its blocks (deps); a block without a finished run makes the
driver fail loudly (Block() needs trajectory.jsonl), it is never silently skipped.

usage: python scripts/a6000/make_tasks_fork_dev.py [--per-task 5] [--write]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path("/data/ziyangs/cloq")
Q = Path("/data/ziyangs/cloq_work/queue")
CK = {"gptq_w4_d1": "gptq", "awq_w4": "awq"}


def producer(model: str, cell: str, blk: str) -> str | None:
    """Queue id of the eval task that writes run a6k2_<model>_<cell>_<blk>."""
    rid = f"a6k2_{model}_{cell}_{blk}"
    for d in ("done", "running", "todo"):
        for f in (Q / d).glob(f"a6k2_{model}_{cell}*.json"):
            t = json.load(open(f))
            if any(r.get("run_id") == rid for r in t.get("runs", [])):
                return t["id"]
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-task", type=int, default=5)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    man = json.load(open(ROOT / "manifests/fork/dev_blocks_v1.json"))
    blocks = list(man["existing_blocks"]) + list(man["new_blocks"])
    tasks = []
    for model, cells in man["cells"].items():
        for cell in cells:
            calib = f"manifests/a6k2/{model}/calib_fp_traj_c1.json"
            ck = {"kind": CK[cell], "wbits": 4, "calib": calib}
            for i in range(0, len(blocks), a.per_task):
                grp = blocks[i:i + a.per_task]
                deps = sorted({p for b in grp if (p := producer(model, cell, b))} | {f"fork_gate_{'q4_gptq_w4_d1' if model == 'q4' else 'q8_awq_w4'}"})
                tasks.append({
                    "id": f"fork_dev_{model}_{cell}_g{i // a.per_task + 1}", "kind": "fork", "model": model,
                    "gpus": 1 if model == "q4" else 2, **({"gpu_util": 0.44} if model == "q4" else {}),
                    "priority": -20, "deps": deps, "q_ckpt": ck, "b_ckpt": {"kind": "bf16"},
                    "fork": {"mode": "dev", "q_blocks": [[f"a6k2_{model}_{cell}_{b}", d] for b in grp for d in ("retail", "airline")],
                             "branches": ["BB", "BQ", "QB"], "noop_frac": 0.1, "q_check": True, "concurrency": 8,
                             "out": f"analysis/fork/dev/{model}_{cell}/g{i // a.per_task + 1}"},
                    "note": "fork-v1 development forks (manifests/fork/dev_blocks_v1.json); generated by make_tasks_fork_dev.py"})
    for t in tasks:
        print(t["id"], t["gpus"], "GPU", len(t["fork"]["q_blocks"]), "block-domains", "deps:", ",".join(t["deps"]))
    if not a.write:
        print(f"{len(tasks)} tasks (dry run; nothing written)")
        return
    for t in tasks:
        if not any((Q / d / f"{t['id']}.json").exists() for d in ("todo", "running", "done", "failed")):
            json.dump(t, open(Q / "todo" / f"{t['id']}.json", "w"), indent=1)


if __name__ == "__main__":
    main()
