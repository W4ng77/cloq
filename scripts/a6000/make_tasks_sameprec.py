"""Same-precision 2x2 fork tasks (W99k, docs/insights/SAMEPREC_PROTOCOL.md): Q = GPTQ-W4 d1 (calibration c1), the
driver's B role = Q' = GPTQ-W4 d2 (calibration c2) of the same model. Exactly the Bank P dev fork pipeline otherwise.

  --gate    one gate task per cell (mode gate on block q3; Q' own blocks a6k2_<m>_gptq_w4_d2_n1 for the Q'Q' no-op)
  --formal  dev-mode tasks over f01..f17 in order, 3 blocks per task (manifests/fork/sameprec_v1.json)
Priority -28; q4 1 GPU (gpu_util 0.44), q8 2 GPUs pinned to node004/005/007 in rotation. Never overwrites an existing id.
usage: python scripts/a6000/make_tasks_sameprec.py (--gate | --formal) [--write]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path("/data/ziyangs/cloq")
Q = Path("/data/ziyangs/cloq_work/queue")
MAN = ROOT / "manifests/fork/sameprec_v1.json"
Q8_NODES = ("node004", "node005", "node007")
PRIO = -28


def ck(m: str, c: str) -> dict:
    return {"kind": "gptq", "wbits": 4, "calib": f"manifests/a6k2/{m}/calib_fp_traj_{c}.json"}


def base(m: str, i: int, tid: str) -> dict:
    pin = {} if m == "q4" else {"node": Q8_NODES[i % len(Q8_NODES)]}
    return {**pin, "id": tid, "kind": "fork", "model": m, "gpus": 1 if m == "q4" else 2,
            **({"gpu_util": 0.44} if m == "q4" else {}), "priority": PRIO, "deps": [],
            "q_ckpt": ck(m, "c1"), "b_ckpt": ck(m, "c2"), "expect_distinct_numerics": True}


def gate_tasks(man: dict) -> list[dict]:
    out = []
    for i, m in enumerate(man["cells"]):
        t = base(m, i, f"fork_sameprec_gate_{m}")
        t["fork"] = {"mode": "gate", "q_blocks": [[f"a6k2_{m}_gptq_w4_d1_q3", d] for d in ("retail", "airline")],
                     "b_blocks": [[f"a6k2_{m}_gptq_w4_d2_n1", d] for d in ("retail", "airline")],
                     "search_tasks_per_block": 6, "n_states": 6, "n_iso": 2, "n_bb_noop": 4, "idcheck_n": 16,
                     "concurrency": 8, "out": f"analysis/fork/sameprec/gate/{m}"}
        t["note"] = "W99k same-precision gate: driver B role = Q' (GPTQ-W4 d2); SAMEPREC_PROTOCOL.md §3"
        out.append(t)
    return out


def formal_tasks(man: dict) -> list[dict]:
    out, blocks, n = [], man["blocks_ordered"], man["blocks_per_task"]
    for m in man["cells"]:
        for gi, i in enumerate(range(0, len(blocks), n)):
            grp = blocks[i:i + n]
            t = base(m, len(out), f"fork_sameprec_{m}_g{gi + 1}")
            t["fork"] = {"mode": "dev", "q_blocks": [[f"a6k2_{m}_gptq_w4_d1_{b}", d] for b in grp for d in ("retail", "airline")],
                         "branches": ["BB", "BQ", "QB"], "noop_frac": 0.1, "q_check": True, "concurrency": 8, "resume": True,
                         "out": f"analysis/fork/sameprec/{m}_gptq_w4_d1_vs_d2/g{gi + 1}"}
            t["note"] = (f"W99k same-precision 2x2 (Q = GPTQ-W4 d1, B role = Q' = GPTQ-W4 d2), blocks {grp}; "
                         "SAMEPREC_PROTOCOL.md; generated by make_tasks_sameprec.py")
            out.append(t)
    return out


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--gate", action="store_true")
    g.add_argument("--formal", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    man = json.load(open(MAN))
    tasks = gate_tasks(man) if a.gate else formal_tasks(man)
    for t in tasks:
        print(t["id"], t["gpus"], "GPU", t.get("node", "-"), len(t["fork"]["q_blocks"]), "block-domains", t["fork"]["out"])
    if not a.write:
        print(f"{len(tasks)} tasks (dry run)")
        return
    n = 0
    for t in tasks:
        if not any((Q / d / f"{t['id']}.json").exists() for d in ("todo", "running", "done", "failed", "deferred")):
            json.dump(t, open(Q / "todo" / f"{t['id']}.json", "w"), indent=1)
            n += 1
    print(f"wrote {n} tasks")


if __name__ == "__main__":
    main()
