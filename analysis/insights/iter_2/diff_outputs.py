def flat(o, p="", out=None):
    out = {} if out is None else out
    if isinstance(o, dict):
        for k, v in o.items():
            flat(v, f"{p}.{k}" if p else str(k), out)
    else:
        out[p] = o
    return out


def fmt(v):
    s = json.dumps(v)
    return s if len(s) <= 60 else s[:57] + "..."


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("old"); ap.add_argument("new"); ap.add_argument("--md", required=True); ap.add_argument("--json")
    a = ap.parse_args()
    old, new = Path(a.old), Path(a.new)
    lines = [f"**TL;DR**", "", "", "", f"# Diff of iter-2 outputs: `{old}` → `{new}`", "",
             "Generated by `analysis/insights/iter_2/diff_outputs.py`. Headline paths are the patterns in its `HEAD` table;",
             "the complete leaf diff (all numbers of all files) is in the JSON companion.", ""]
    full = {}; tot_changed = tot_head = 0; summary = []; keyrows = []
    for f in sorted(set(HEAD) | {p.name for p in new.glob("*.json") if not p.name.startswith(("snapshot_", "diff_"))}):
        po, pn = old / f, new / f
        if not pn.exists() and not po.exists():
            continue
        A = flat(json.load(open(po))) if po.exists() else {}
        B = flat(json.load(open(pn))) if pn.exists() else {}
        keys = sorted(set(A) | set(B))
        ch = {k: [A.get(k, "<absent>"), B.get(k, "<absent>")] for k in keys if A.get(k, "<absent>") != B.get(k, "<absent>")
              and not k.endswith(("snapshot_utc", "utc", "_frozen_snapshot.id", "_frozen_snapshot.path"))}
        full[f] = ch
        pats = HEAD.get(f, [])
        hk = [k for k in keys if any(fnmatch(k, p) for p in pats) and not any(fnmatch(k, x) for x in EXCLUDE)]
        kk = [k for k in keys if any(fnmatch(k, p) for p in KEY.get(f, []))]
        for k in kk:
            o, n = A.get(k, "<absent>"), B.get(k, "<absent>")
            d = f"{n - o:+.4g}" if isinstance(o, (int, float)) and isinstance(n, (int, float)) and not isinstance(o, bool) else ""
            keyrows.append(f"| {f} | `{k}` | {fmt(o)} | {fmt(n)} | {d} |")
        hch = [k for k in hk if k in ch]
        tot_changed += len(ch); tot_head += len(hch)
        summary.append((f, "new file" if not po.exists() else ("removed" if not pn.exists() else ""), len(keys), len(ch), len(hk), len(hch)))
        if hch:
            lines += [f"## {f}", "", "| path | old | new | Δ |", "|---|---|---|---|"]
            for k in hch:
                o, n = ch[k]
                d = f"{n - o:+.4g}" if isinstance(o, (int, float)) and isinstance(n, (int, float)) and not isinstance(o, bool) else ""
                lines.append(f"| `{k}` | {fmt(o)} | {fmt(n)} | {d} |")
            lines.append("")
    head = ["## Summary", "", "| file | status | leaves | changed | headline leaves | headline changed |", "|---|---|---|---|---|---|"]
    head += [f"| {f} | {s} | {n} | {c} | {h} | {hc} |" for f, s, n, c, h, hc in summary]
    lines[1] = (f"- {tot_head} headline numbers changed ({tot_changed} leaves in total) between the previous outputs and "
                f"this frozen-snapshot run; per-file counts in the summary table, every changed headline path below.")
    lines[2] = f"- evidence: old `{old}`, new `{new}`; full leaf diff `{a.json or '(not written)'}`."
    lines[3] = "- Numbers from runs still in flight are provisional; re-run `bash analysis/insights/iter_2/run_all.sh` after the redos."
    key = ["## Key numbers quoted in iter_2_prep.md / iter_2_conformal.md (old → new, changed or not)", "",
           "| file | path | old | new | Δ |", "|---|---|---|---|---|"] + keyrows + [""]
    lines = lines[:9] + head + [""] + key + ["# All changed headline numbers", ""] + lines[9:]
    Path(a.md).write_text("\n".join(lines) + "\n")
    if a.json:
        json.dump(full, open(a.json, "w"), indent=0, default=str)
    print(f"headline changed {tot_head}, all changed {tot_changed} -> {a.md}")


if __name__ == "__main__":
    main()
