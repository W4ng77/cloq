#!/usr/bin/env python3
"""Generate appendix tables (new-task intervals for G/H/F; 16 outcome patterns) verbatim from the W93 report.

Input:  analysis/fork/out/ghf_20261001T211519Z.md (sections 1 and 3).
Output: paper/latex/sections/gen_ghf_crossed.tex, paper/latex/sections/gen_patterns.tex
No number is computed here; cells are copied from the markdown tables and only re-formatted for LaTeX.
Usage: python3 paper/latex/tools/gen_w93_tables.py
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC = "analysis/fork/out/ghf_20261001T211519Z.md"
OUT = os.path.join(ROOT, "paper", "latex", "sections")
NAME = {"q4:awq_w4": "q4 AWQ-W4", "q4:gptq_w4_d1": "q4 GPTQ-W4", "q8:awq_w4": "q8 AWQ-W4",
        "q8:gptq_w4_d1": "q8 GPTQ-W4", "q4:kvq_int8": "q4 KV8", "q8:kvq_int8": "q8 KV8",
        "q4:gptq_w3": "q4 GPTQ-W3$^s$", "q4:kvq_int4_rot": "q4 KV4-rot$^s$", "q8:gptq_w3": "q8 GPTQ-W3$^s$",
        "q8:kvq_int4_rot": "q8 KV4-rot$^s$", "q8:rtn_w3": "q8 RTN-W3$^s$"}
ORDER = ["q4:gptq_w4_d1", "q4:awq_w4", "q8:gptq_w4_d1", "q8:awq_w4", "q4:kvq_int8", "q8:kvq_int8",
         "q4:gptq_w3", "q4:kvq_int4_rot", "q8:gptq_w3", "q8:kvq_int4_rot", "q8:rtn_w3"]


def tex_num(s):
    s = s.strip()
    return re.sub(r"([+-]?\d+\.\d+)", lambda m: "$" + m.group(1).replace("-", "-") + "$", s)


def table_after(lines, header_start):
    i = next(k for k, l in enumerate(lines) if l.startswith(header_start))
    rows = []
    for l in lines[i + 2:]:
        if not l.startswith("|"):
            break
        rows.append([c.strip() for c in l.strip().strip("|").split("|")])
    return lines[i], rows


def main():
    lines = open(os.path.join(ROOT, SRC), encoding="utf-8").read().split("\n")
    # new-task (crossed) intervals, per cell
    i = next(k for k, l in enumerate(lines) if l.startswith("New-task generalisation"))
    _, rows = table_after(lines[i:], "| cell | G | H | F |")
    by = {r[0]: r[1:] for r in rows}
    # pools: second line of each cell (after <br>) is the crossed interval
    _, prow = table_after(lines, "| pool | cells | blocks |")
    pools = {r[0]: [c.split("<br>")[1] if "<br>" in c else "" for c in r[3:]] for r in prow}
    out = ["% GENERATED by paper/latex/tools/gen_w93_tables.py -- do not edit by hand.",
           "% src: " + SRC + " (§1 new-task generalisation table; pools, second line = crossed)",
           "\\begin{table*}[t]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
           "% src: " + SRC,
           "\\begin{tabular}{@{}lllllll@{}}", "\\toprule",
           "Cell & $G$ & $H$ & $F$ & $G-H$ & $F-G$ & $F-H$ \\\\", "\\midrule"]
    for c in ORDER:
        out.append(NAME[c] + " & " + " & ".join(tex_num(v) for v in by[c]) + " \\\\")
        if c == "q8:awq_w4":
            out.append("W4 pool & " + " & ".join(tex_num(v) for v in pools["W4:all"]) + " \\\\")
        if c == "q8:kvq_int8":
            out.append("KV8 pool & " + " & ".join(tex_num(v) for v in pools["KV8:all"]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}",
            "\\caption{New-task generalisation: crossed task$\\times$block bootstrap 95\\% intervals for the estimates of "
            "Table~\\ref{tab:ghf} (pp; same Bank P states). These answer whether the effect would hold for new tasks "
            "drawn like the panel; the fixed-pool intervals of Table~\\ref{tab:ghf} treat the 85 tasks as fixed. "
            "$^s$stress cell, 3 blocks.}",
            "\\label{tab:ghf-crossed}", "\\end{table*}", ""]
    open(os.path.join(OUT, "gen_ghf_crossed.tex"), "w").write("\n".join(out))

    # 16 patterns
    hdr, rows = table_after(lines, "| pattern |")
    cols = [c.strip() for c in hdr.strip().strip("|").split("|")][1:]
    short = {"q4:awq_w4": "q4 AWQ", "q4:gptq_w3": "q4 GPTQ-W3", "q4:gptq_w4_d1": "q4 GPTQ", "q4:kvq_int4_rot": "q4 KV4r",
             "q4:kvq_int8": "q4 KV8", "q8:awq_w4": "q8 AWQ", "q8:gptq_w3": "q8 GPTQ-W3", "q8:gptq_w4_d1": "q8 GPTQ",
             "q8:kvq_int4_rot": "q8 KV4r", "q8:kvq_int8": "q8 KV8", "q8:rtn_w3": "q8 RTN-W3"}
    out = ["% GENERATED by paper/latex/tools/gen_w93_tables.py -- do not edit by hand.",
           "\\begin{table*}[t]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}",
           "% src: " + SRC + " (§3 All 16 outcome patterns)",
           "\\resizebox{\\textwidth}{!}{\\begin{tabular}{@{}l" + "r" * len(cols) + "@{}}", "\\toprule",
           "$(\\YY{BB},\\YY{BQ},\\YY{QB},\\YY{QQ})$ & " + " & ".join(short[c] for c in cols) + " \\\\", "\\midrule"]
    for r in rows:
        lab = r[0]
        if lab == "n":
            out.append("\\midrule")
            out.append("$n$ & " + " & ".join(r[1:]) + " \\\\")
        else:
            out.append("\\texttt{" + lab + "} & " + " & ".join(v.replace("%", "\\%") for v in r[1:]) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}}",
            "\\caption{All 16 four-branch outcome patterns per cell: count (share of the cell's Bank P states). "
            "Pattern digits are $(\\YY{BB},\\YY{BQ},\\YY{QB},\\YY{QQ})$. KV4r: Q/K-rotated KV4; W3 and KV4r cells are "
            "stress cells with 3 blocks.}",
            "\\label{tab:patterns}", "\\end{table*}", ""]
    open(os.path.join(OUT, "gen_patterns.tex"), "w").write("\n".join(out))
    print("wrote gen_ghf_crossed.tex, gen_patterns.tex")


if __name__ == "__main__":
    main()
