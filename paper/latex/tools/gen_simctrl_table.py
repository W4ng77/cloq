"""W96: appendix table of the Bank U simulator control (W95) fates, with the flagged-reply sensitivity (GPT-6.1 review 7).
usage: python paper/latex/tools/gen_simctrl_table.py -> paper/latex/sections/gen_simctrl_fates.tex"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MAIN = "analysis/fork/out/simctrl_20261001T212742Z"
SENS = "analysis/fork/out/simctrl_relay_flagged_20261001T225847Z"
m, s = (json.load(open(ROOT / f"{p}.json")) for p in (MAIN, SENS))
ci = lambda c: f"[{c[0]:.2f}, {c[1]:.2f}]"  # noqa: E731


def row(name, d):
    f, c = d["flips"]["all"], d["controls"]["all"]
    return (f"{name} & {f['n_ok']} & {f['retained']} {ci(f['retained_ci95'])} & {f['reversed']} & {f['vanished']} "
            f"({f['vanished_both_succeed']}/{f['vanished_both_fail']}/{f['vanished_tie_mixed']}) & {c['n_ok']} & {c['new_flips']} {ci(c['new_flips_ci95'])} ({c['new_rescue']}/{c['new_damage']}) \\\\")


v = m["variability"]
pr = m["flips"]["all"]["per_replicate"]
L = ["% GENERATED by paper/latex/tools/gen_simctrl_table.py -- do not edit by hand.",
     f"% src: {MAIN}.md; {SENS}.md",
     "\\begin{table}[h]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}", "\\resizebox{\\columnwidth}{!}{\\begin{tabular}{@{}lrllrrl@{}}", "\\toprule",
     "Analysis & flips & retained & rev. & vanished (s/f/tie) & ctrl & new flips (resc./dam.) \\\\", "\\midrule",
     row("All replies", m), row("Flagged dropped", s), "\\bottomrule", "\\end{tabular}}",
     "\\caption{Bank U simulator control (block f01; Sonnet 5.5 relay user, $R=3$). Fates use the sign of the replicate-mean flip "
     "indicator; s/f: both arms succeed/fail. ``Flagged dropped'': the two arm replicates with a mechanically flagged reply are set to "
     f"missing. Replicates of one arm disagree in {v['flip:BQ']['replicates_disagree']}/{v['flip:BQ']['n']} (BQ) and "
     f"{v['flip:QQ']['replicates_disagree']}/{v['flip:QQ']['n']} (QQ) flip states and in {v['control:BQ']['replicates_disagree']}/39 and "
     f"{v['control:QQ']['replicates_disagree']}/39 control states. Per single replicate, retained flips are "
     f"{pr['0']['retained']}, {pr['1']['retained']} and {pr['2']['retained']} of 39. "
     "Source: \\nolinkurl{" + MAIN + ".md}, \\nolinkurl{" + SENS + ".md}.}",
     "\\label{tab:simctrl}", "\\end{table}", ""]
(ROOT / "paper/latex/sections/gen_simctrl_fates.tex").write_text("\n".join(L))
print("\n".join(L))
