#!/usr/bin/env python3
"""Present fixed-pool and crossed intervals together, using the frozen G/H/F output."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
PAPER=Path(__file__).resolve().parents[1]
SRC='analysis/fork/out/ghf_20261001T211519Z.json'
x=json.loads((ROOT/SRC).read_text())
rows=[('q4:gptq_w4_d1','q4 GPTQ-W4'),('q4:awq_w4','q4 AWQ-style W4'),('q8:gptq_w4_d1','q8 GPTQ-W4'),('q8:awq_w4','q8 AWQ-style W4'),('W4:all','W4 pool'),('q4:kvq_int8','q4 KV8'),('q8:kvq_int8','q8 KV8'),('KV8:all','KV8 pool'),('q4:gptq_w3',r'q4 GPTQ-W3$^s$'),('q4:kvq_int4_rot',r'q4 KV4-rot$^s$'),('q8:gptq_w3',r'q8 GPTQ-W3$^s$'),('q8:kvq_int4_rot',r'q8 KV4-rot$^s$'),('q8:rtn_w3',r'q8 RTN-W3$^s$')]
def sign(v):
    if abs(v)<.05:v=0.
    return f'${v:+.1f}$'
def bounds(ci):return '['+', '.join(sign(v) for v in ci)+']'
def paired(s):
    return r'\shortstack[l]{'+sign(s['est'])+' '+bounds(s['ci95'])+r'\\{}'+bounds(s['crossed_ci95'])+'}'
header=r'''% GENERATED by tools/gen_ghf_combined.py; display only, no analysis changes.
% src: analysis/fork/out/ghf_20261001T211519Z.json; analysis/fork/out/ghf_20261001T211519Z.md; analysis/fork/out/ghf_multiplicity_20261001T225727Z.md
\begin{table*}[t]
\centering\fontsize{9}{11}\selectfont
\renewcommand{\arraystretch}{1.15}\setlength{\tabcolsep}{4pt} % nocheck: layout
'''
out=[]
for n in [0,1]:
    out.append(header)
    cols=6 if n==0 else 7
    out.append(r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}'+('ll'+'l'*4 if n==0 else 'l'*6)+r'@{}}'+'\n'+r'\toprule'+'\n')
    out.append(('Cell & states & $G$ (action) & $H$ (continuation) & $F$ (joint) & $G-H$' if n==0 else r'Cell & $F-G$ & $F-H$ & off-diag.\ \% & rev.\ \% & mean $I$')+r' \\'+'\n'+r'\midrule'+'\n')
    for i,(key,label) in enumerate(rows):
        c=x['cells'].get(key,x['pools'].get(key));s=c['stats']
        if i in [5,8]:out.append(r'\midrule'+'\n')
        if n==0: vals=[label,str(c.get('n_states',c.get('n_states_summed')))]+[paired(s[k]) for k in ['G','H','F','GmH']]
        else: vals=[label]+[paired(s[k]) for k in ['FmG','FmH']]+[f"{s[k]['est']:.1f}" for k in ['offdiag','strict_reversal']]+[sign(s['I']['est'])]
        out.append(' & '.join(vals)+r' \\'+'\n'+r'\addlinespace[1pt] % nocheck: layout'+'\n')
    out.append(r'\bottomrule'+'\n'+r'\end{tabular*}'+'\n')
    if n==0:
        out.append(r'''\caption{Upgrade gains on divergent states (pp). In each two-line cell, the first line gives the estimate and fixed-pool 95\% interval; the second gives the new-task crossed 95\% interval. $G$, $H$ and $F$ compare action-only, continuation-only and joint replacement with QQ. Fixed-pool intervals use a block bootstrap over 20--22 blocks, or a $t$ interval over three blocks for $^s$stress configurations. Pools average within-configuration estimates equally; stress configurations are separate.}
\label{tab:ghf}
\label{tab:ghf-crossed}
''')
    else:
        out.append(r'''\caption{Paired mode contrasts and outcome patterns on the states of Table~\ref{tab:ghf}. Two-line cells give fixed-pool and new-task 95\% intervals in that order. Off-diag.: $\DQ\ne\DB$; rev.: $\DQ=-\DB\ne0$; interaction $I=\DQ-\DB$. Intervals are unadjusted. The four core W4 $G-H$ tests form a Holm family: q4 GPTQ-W4 has adjusted $p=.069$; all four new-task intervals cover zero. A positive $G-H$ compares two upgrades, not either upgrade against QQ.}
\label{tab:ghf-patterns}
''')
    out.append(r'\end{table*}'+'\n\n')
(PAPER/'sections/gen_ghf_combined.tex').write_text(''.join(out))
